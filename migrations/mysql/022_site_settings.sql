CREATE TABLE site_settings (
 id SMALLINT NOT NULL PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 description VARCHAR(1000) NOT NULL,
 announcement TEXT NOT NULL,
 registration SMALLINT NOT NULL DEFAULT 1,
 email_mode SMALLINT NOT NULL DEFAULT 0,
 email_domains TEXT NOT NULL,
 max_players SMALLINT NOT NULL DEFAULT 20,
 single_session SMALLINT NOT NULL DEFAULT 0,
 sign_enabled SMALLINT NOT NULL DEFAULT 1,
 sign_hours INTEGER NOT NULL DEFAULT 24,
 sign_min BIGINT NOT NULL DEFAULT 10,
 sign_max BIGINT NOT NULL DEFAULT 100,
 initial_points BIGINT NOT NULL DEFAULT 1000,
 player_cost BIGINT NOT NULL DEFAULT 100,
 oauth_enabled SMALLINT NOT NULL DEFAULT 0
);
